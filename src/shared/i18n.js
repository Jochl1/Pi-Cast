/**
 * Returns tr(key, vars) for `lang` (English for unknown languages or keys);
 * tr.locale is the locale for dates.
 */
export function translator(lang) {
  const table = STRINGS[lang] ?? STRINGS.en;
  const tr = (key, vars = {}) => (table[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  tr.lang = STRINGS[lang] ? lang : 'en';
  tr.locale = LANGUAGES[tr.lang].locale;
  return tr;
}
